#!/usr/bin/env bash
# repo-map.sh — walk ~/dev/projects read-only, print the live estate, and flag
# drift against the hand-kept map (docs/operations/systems/repo-map/01-repos.md).
#
# Same shape as bucket-tree/bucket-drift: structure is DERIVED, meaning is
# HAND-KEPT, drift is reported rather than silently overwritten. --update
# refreshes only the marked generated block; the authored prose is never touched.
set -euo pipefail

usage() {
  cat <<'EOF'
repo-map.sh — the live repo estate + drift against the hand-kept map.

USAGE
  repo-map.sh              print the estate and flag drift (exit 1 on drift)
  repo-map.sh --update     refresh the generated block in 01-repos.md
  repo-map.sh --list       plain repo list, one per line (for piping)

WHAT IT READS
  ~/dev/projects           every .git up to 3 levels deep
  docs/operations/systems/repo-map/01-repos.md   the map it checks against

DRIFT = a repo on disk the map never mentions, or a repo the map names that
is no longer there. Meaning columns are yours; this only watches structure.
EOF
}

ROOT="${REPO_ROOT:-$HOME/dev/projects}"
DOT="${DOT:-$HOME/.dotfiles}"
MAP="$DOT/docs/operations/systems/repo-map/01-repos.md"

case "${1:-}" in -h|--help) usage; exit 0 ;; esac

# --- the walk (read-only) ---------------------------------------------------
repos() { find "$ROOT" -maxdepth 3 -name .git -type d 2>/dev/null \
            | sed "s|/.git||; s|^$ROOT/||" | sort; }

attrs() { # repo -> "docs kol memory pkg"
  local p="$ROOT/$1"
  printf '%s %s %s %s' \
    "$([ -d "$p/docs" ] && echo docs || echo ----)" \
    "$([ -d "$p/.kol" ] && echo .kol || echo ----)" \
    "$([ -d "$p/.kol/llm-memory" ] && echo mem || echo ---)" \
    "$([ -f "$p/package.json" ] && echo pkg || echo ---)"
}

# families = dirs holding repos but not repos themselves
families() {
  find "$ROOT" -maxdepth 1 -mindepth 1 -type d 2>/dev/null | while read -r d; do
    [ -d "$d/.git" ] && continue
    n=$(find "$d" -maxdepth 2 -name .git -type d 2>/dev/null | wc -l | tr -d ' ')
    [ "$n" -gt 0 ] && printf '%s %s\n' "${d##*/}" "$n"
  done | sort
}

if [ "${1:-}" = "--list" ]; then repos; exit 0; fi

# --card: generate the ref-repo card FROM the map, so the shell surface and the
# vault surface can't drift — one source (01-repos.md), two readers.
if [ "${1:-}" = "--card" ]; then
  CARD="$DOT/ref/repo.md"
  python3 - "$MAP" "$CARD" <<'PY'
import re, sys
src, out = sys.argv[1], sys.argv[2]
text = open(src).read()
rows = re.findall(r'^\| \*\*([a-z0-9-]+)\*\* \| (.+?) \| (.+?) \|$', text, re.M)

# Cells stay glance-length — `ref --lint` fails anything over 46 chars, and the
# old 120 cut left sentences severed mid-word ("the hooks that enforce the |").
# Cut at a WORD boundary and mark it, so the reader knows depth was evicted.
def cell(s, n=46):
    s = s.strip()
    if len(s) <= n:
        return s
    cut = s[:n - 1]
    if ' ' in cut:
        cut = cut[:cut.rindex(' ')]
    return cut + '…'
L = ['# repo — quick reference', '',
     'Filter: `ref-repo <word …>` · 29 repos · 6 top-level + 2 families',
     'generated by `repo-map.sh --card` from docs/operations/systems/repo-map/01-repos.md', '']
for name, what, wires in rows:
    what = re.sub(r'`([^`]*)`', r'\1', what)
    wires = re.sub(r'`([^`]*)`', r'\1', wires)
    # NO spacer row between the two data rows — a blank row is a CATEGORY break
    # only (user ruling 2026-07-31; this generator was re-emitting them).
    L += [f'## {name}', '',
          '| keys     | does |', '|----------|------|',
          f'| is       | {cell(what)} |',
          f'| wires    | {cell(wires)} |', '']
L += ['## apps', '',
      '| keys   | does |', '|--------|------|',
      '| family | kol-apps — 20 repos, no shared build |',
      '| client | ac · acyr · aftra · canalix · kolkrabbi |',
      '| live   | kol-monitor · kol-chrome-vcap |', '',
      '## wiring', '',
      '| keys      | does |', '|-----------|------|',
      '| publisher | kol-ds-ui — 15 @kolkrabbi packages |',
      '| consumers | website 10 · chess 6 · fxr 4 · showcase 11 |',
      '| agent     | humpty muzzle · jabberwocky OS · glass mem |',
      '| lens      | kol-glass — symlinks, never fix it here |', '',
      '----', 'doc: docs/operations/systems/repo-map/INDEX.md', '']
open(out, 'w').write('\n'.join(L))
print(f'card written: {out} ({len(rows)} repo sections)')
PY
  exit 0
fi

generated_block() {
  local all; all=$(repos)
  printf '### Generated — the live estate (`repo-map.sh --update`, %s)\n\n' "$(date +%F)"
  printf '%s repos · %s families\n\n' "$(printf '%s\n' "$all" | wc -l | tr -d ' ')" \
                                      "$(families | wc -l | tr -d ' ')"
  printf '| repo | docs | .kol | memory | package |\n|---|---|---|---|---|\n'
  printf '%s\n' "$all" | while read -r r; do
    [ -z "$r" ] && continue
    set -- $(attrs "$r")
    printf '| `%s` | %s | %s | %s | %s |\n' "$r" \
      "$([ "$1" = docs ] && echo ✓ || echo ·)" \
      "$([ "$2" = .kol ] && echo ✓ || echo ·)" \
      "$([ "$3" = mem ]  && echo ✓ || echo ·)" \
      "$([ "$4" = pkg ]  && echo ✓ || echo ·)"
  done
}

# --- drift ------------------------------------------------------------------
drift=0
missing=""
for r in $(repos); do
  grep -q -- "${r##*/}" "$MAP" 2>/dev/null || { missing+="  + $r (on disk, not in the map)"$'\n'; drift=1; }
done

if [ "${1:-}" = "--update" ]; then
  [ -f "$MAP" ] || { echo "repo-map: no map at $MAP" >&2; exit 1; }
  grep -q '^<!-- GENERATED:' "$MAP" || { echo "repo-map: no GENERATED markers in $MAP" >&2; exit 1; }
  # splice by markers — sed slices, no awk -v (a multi-line -v value breaks awk)
  tmp=$(mktemp)
  {
    sed -n '1,/^<!-- GENERATED:/p' "$MAP"
    printf '\n'
    generated_block
    printf '\n'
    sed -n '/^<!-- \/GENERATED/,$p' "$MAP"
  } > "$tmp" && mv "$tmp" "$MAP"
  echo "✅ generated block refreshed in ${MAP/#$HOME/~}"
  [ -n "$missing" ] && printf '\n⚠ meaning rows still missing (author them by hand):\n%s' "$missing"
  exit 0
fi

generated_block
if [ -n "$missing" ]; then
  printf '\n⚠ DRIFT — the map has not heard of:\n%s\nAuthor a row in %s, then: repo-map.sh --update\n' \
    "$missing" "${MAP/#$HOME/~}"
  exit 1
fi
echo
echo "✓ no drift — every repo on disk appears in the map"
